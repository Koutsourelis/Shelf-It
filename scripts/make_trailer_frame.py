"""Build the last frame of the trailer: the demo shelf photo on a phone held in landscape, camera open.

The frame is composed here, not generated by a model, so the shelf the judges see on the phone is exactly the
photo the agent analyses next. The phone shows a plain camera viewfinder (photo plus shutter button), which is
what the capture page opens on a real phone. Details in pitch/TRAILER.md.

    python scripts/make_trailer_frame.py data/shelf/photos/<photo>.jpg
    python scripts/make_trailer_frame.py <photo> --out pitch/trailer/end_frame.png --size 1920x1080
"""
from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageEnhance, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "pitch" / "trailer" / "end_frame.png"
PHONE_RATIO = 2.1  # long side / short side of a current phone body


def cover(img: Image.Image, size: tuple[int, int]) -> Image.Image:
    """Scale and centre-crop img so it fills size exactly."""
    w, h = size
    scale = max(w / img.width, h / img.height)
    resized = img.resize((round(img.width * scale), round(img.height * scale)), Image.LANCZOS)
    left, top = (resized.width - w) // 2, (resized.height - h) // 2
    return resized.crop((left, top, left + w, top + h))


def contain(img: Image.Image, size: tuple[int, int]) -> Image.Image:
    """Scale img to fit inside size, keeping its proportions."""
    w, h = size
    scale = min(w / img.width, h / img.height)
    return img.resize((round(img.width * scale), round(img.height * scale)), Image.LANCZOS)


def rounded_mask(size: tuple[int, int], radius: int) -> Image.Image:
    mask = Image.new("L", size, 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, size[0] - 1, size[1] - 1), radius=radius, fill=255)
    return mask


def viewfinder(photo: Image.Image, size: tuple[int, int]) -> Image.Image:
    """Black camera screen: the photo on the left, a white shutter button in a strip on the right."""
    w, h = size
    screen = Image.new("RGB", size, (0, 0, 0))
    strip = round(w * 0.14)
    shot = contain(photo, (w - strip, h))
    screen.paste(shot, ((w - strip - shot.width) // 2, (h - shot.height) // 2))

    draw = ImageDraw.Draw(screen)
    cx, cy, r = w - strip // 2, h // 2, round(h * 0.08)
    ring = max(3, round(r * 0.12))
    draw.ellipse((cx - r, cy - r, cx + r, cy + r), outline=(255, 255, 255), width=ring)
    inner = r - ring * 2
    draw.ellipse((cx - inner, cy - inner, cx + inner, cy + inner), fill=(255, 255, 255))
    return screen


def build_frame(photo: Image.Image, size: tuple[int, int]) -> Image.Image:
    w, h = size
    # Behind the phone: the same shelf, out of focus and darker.
    frame = cover(photo, size).filter(ImageFilter.GaussianBlur(radius=w / 60))
    frame = ImageEnhance.Brightness(frame).enhance(0.55)

    body_w = round(w * 0.94)
    body_h = round(body_w / PHONE_RATIO)
    if body_h > h * 0.92:
        body_h = round(h * 0.92)
        body_w = round(body_h * PHONE_RATIO)
    x, y = (w - body_w) // 2, (h - body_h) // 2
    radius = round(body_h * 0.11)

    # Soft shadow under the phone.
    shadow = Image.new("L", size, 0)
    offset = round(h * 0.015)
    ImageDraw.Draw(shadow).rounded_rectangle(
        (x, y + offset, x + body_w, y + body_h + offset), radius=radius, fill=170)
    shadow = shadow.filter(ImageFilter.GaussianBlur(radius=h / 40))
    frame.paste(Image.new("RGB", size, (0, 0, 0)), (0, 0), shadow)

    # Phone body with a thin lighter edge, then the screen inside the bezel.
    body = Image.new("RGB", (body_w, body_h), (42, 47, 54))
    core = Image.new("RGB", (body_w - 4, body_h - 4), (14, 16, 19))
    body.paste(core, (2, 2), rounded_mask(core.size, radius - 2))
    bezel = round(body_h * 0.025)
    screen_size = (body_w - 2 * bezel, body_h - 2 * bezel)
    screen = viewfinder(photo, screen_size)
    body.paste(screen, (bezel, bezel), rounded_mask(screen_size, round(body_h * 0.09)))
    frame.paste(body, (x, y), rounded_mask((body_w, body_h), radius))
    return frame


def parse_size(text: str) -> tuple[int, int]:
    w, _, h = text.lower().partition("x")
    return int(w), int(h)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("photo", type=Path, help="the demo shelf photo")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help=f"output PNG (default: {DEFAULT_OUT.relative_to(ROOT)})")
    parser.add_argument("--size", type=parse_size, default=(1920, 1080), help="frame size, WxH (default: 1920x1080)")
    args = parser.parse_args()

    photo = Image.open(args.photo).convert("RGB")
    frame = build_frame(photo, args.size)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    frame.save(args.out)
    print(f"{args.out} ({frame.width}x{frame.height}) from {args.photo} ({photo.width}x{photo.height})")


if __name__ == "__main__":
    main()
