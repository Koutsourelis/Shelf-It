"""Prompts του μοντέλου όρασης. Κάτοχος: Άτομο Α.

Κάθε αλλαγή εδώ μετριέται με `python scripts/eval_vision.py` πριν μπει στο main.
Ανέβασε το PROMPT_VERSION όταν αλλάζεις κάτι: μπαίνει στο cache key και στα αποτελέσματα του eval.
"""

PROMPT_VERSION = "v8"   # v8: κενά (gaps) = γέμισμα, ξένο μόνο ό,τι δεν πουλιέται σε τέτοιο ράφι· v7: επίπεδο-στόχος και λόγος ανά ομάδα, γέμισμα σε ράφι εκτός καταλόγου· v6: μάρκα και πλήρες όνομα ανά ομάδα (ταυτότητα από Open Food Facts, agentkit/identity.py)

SYSTEM = (
    "Διαβάζεις φωτογραφίες ραφιών καταστήματος. Καταγράφεις μόνο ό,τι φαίνεται καθαρά· δεν μαντεύεις και δεν "
    "συμπληρώνεις ό,τι θα περίμενες να υπάρχει. Αν ένα προϊόν δεν ταιριάζει με βεβαιότητα σε κωδικό του καταλόγου, "
    "δίνεις sku null και γράφεις στο label ό,τι διαβάζεις. Μετράς μόνο την μπροστινή σειρά."
)

# Κανόνες παρουσίασης που θέλουν «μάτι». Οι κανόνες που ελέγχονται από αριθμούς (θέση, προσόψεις, ύψος ματιών)
# γίνονται στον κώδικα (check_planogram, layout_suggestions), όχι εδώ.
VISUAL_RULES = [
    "Η μπροστινή όψη κάθε συσκευασίας κοιτάει προς τα έξω (αλλιώς label_not_facing).",
    "Τα προϊόντα είναι τραβηγμένα μπροστά στην άκρη του ραφιού (αλλιώς not_fronted).",
    "Τα ίδια προϊόντα στέκονται μαζί, όχι ανακατεμένα με άλλα (αλλιώς messy).",
]

# Δύσκολες περιπτώσεις ανάγνωσης. Κάθε γραμμή εδώ πρέπει να δικαιολογείται από λάθος που φάνηκε στο eval.
READING_HINTS = [
    "Οι ετικέτες μπορεί να είναι στα ελληνικά, στα αγγλικά ή και στα δύο. Στο label γράψε το κείμενο όπως "
    "ακριβώς φαίνεται, χωρίς μετάφραση ή μεταγραφή· ταίριαξε με τον κατάλογο ανεξάρτητα από γλώσσα, τόνους και κεφαλαία.",
    "Παρόμοιες συσκευασίες της ίδιας μάρκας (π.χ. 100g και 200g, διαφορετική γεύση ή χρώμα) είναι διαφορετικοί "
    "κωδικοί. Ξεχώρισέ τες από το βάρος ή τον όγκο που γράφει η συσκευασία και από το σχετικό μέγεθος δίπλα στα "
    "γειτονικά προϊόντα. Αν δεν διαβάζεται ποια παραλλαγή είναι, sku null.",
    "Αντανακλάσεις, γυαλάδα ή θολούρα μπορεί να κρύβουν μέρος της ετικέτας: βασίσου σε ό,τι διαβάζεται καθαρά "
    "(λογότυπο, χρώμα, σχήμα) και μη συμπληρώνεις γράμματα που δεν φαίνονται. Αν δεν αρκούν, sku null.",
    "Ετικέτες τιμών στην άκρη του ραφιού, αφίσες και ταμπέλες δεν είναι προϊόντα και δεν μπαίνουν στο items.",
    "Το box_2d κάθε εγγραφής περικλείει όλη την ομάδα (όλες τις προσόψεις της), όχι ένα μόνο τεμάχιο.",
]


def user_prompt(catalog: list[tuple[str, str, str]], has_reference: bool) -> str:
    listing = "\n".join(f"{sku} | {name} | {brand}" for sku, name, brand in catalog)
    ref = ("Η ΠΡΩΤΗ εικόνα είναι το ίδιο ράφι σωστά γεμάτο (αναφορά). Η ΔΕΥΤΕΡΗ είναι η τωρινή κατάσταση. "
           "Περίγραψε ΜΟΝΟ τη δεύτερη· την πρώτη χρησιμοποίησε για να αναγνωρίζεις προϊόντα και θέσεις.\n\n"
           if has_reference else "")
    rules = "\n".join(f"- {r}" for r in VISUAL_RULES)
    hints = "\n".join(f"- {h}" for h in READING_HINTS)
    return (
        f"{ref}Κατάλογος προϊόντων (κωδικός | προϊόν | μάρκα):\n{listing}\n\n"
        "Διάβασε τη φωτογραφία του ραφιού. Για κάθε ομάδα ίδιων προϊόντων που στέκονται δίπλα δίπλα δώσε μία "
        "εγγραφή στο items, από πάνω προς τα κάτω και από αριστερά προς τα δεξιά. Στο gaps βάλε κάθε εμφανές κενό. "
        "Αν κάποιος ή κάτι κρύβει μέρος του ραφιού, occluded = true.\n\n"
        f"Δύσκολες περιπτώσεις:\n{hints}\n\n"
        f"Κανόνες παρουσίασης· κάθε παράβαση πάει στο visual_issues:\n{rules}"
    )
